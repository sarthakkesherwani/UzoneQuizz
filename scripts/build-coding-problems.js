#!/usr/bin/env node
/* Assembles scripts/lc-data/*.json into coding-problems.js (the browser data
   file for the Code practice feature), keeping the question-bank's ordering.
   Refuses to emit a file containing an invalid spec.

   Usage: node scripts/build-coding-problems.js */
'use strict';

const fs = require('fs');
const path = require('path');
const harness = require(path.join(__dirname, '..', 'coding-harness.js'));
const bank = require(path.join(__dirname, '..', 'question-bank.js'));

const dataDir = path.join(__dirname, 'lc-data');
const bankOrder = [].concat(...Object.values(bank.leetcodeQuestions || {})).map(q => q.id);

const files = fs.readdirSync(dataDir).filter(f => f.endsWith('.json'));
const specs = [];
let invalid = 0;
for (const file of files) {
  const spec = JSON.parse(fs.readFileSync(path.join(dataDir, file), 'utf8'));
  const errors = harness.validateSpec(spec);
  if (errors.length) {
    invalid++;
    console.error(`INVALID ${file}:`);
    errors.forEach(e => console.error(`  - ${e}`));
    continue;
  }
  specs.push(spec);
}
if (invalid) { console.error(`\n${invalid} invalid spec(s) — coding-problems.js NOT written`); process.exit(1); }

specs.sort((a, b) => {
  const ia = bankOrder.indexOf(a.id), ib = bankOrder.indexOf(b.id);
  return (ia === -1 ? 1e9 : ia) - (ib === -1 ? 1e9 : ib);
});

const missing = bankOrder.filter(id => !specs.some(s => s.id === id));
if (missing.length) console.warn(`WARNING: ${missing.length} bank problem(s) have no spec yet: ${missing.join(', ')}`);

const out = `/* Generated by scripts/build-coding-problems.js — do not edit by hand.
   ${specs.length} problems. Rebuild with: node scripts/build-coding-problems.js */
'use strict';
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.UzoneCodingProblems = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  return ${JSON.stringify(specs, null, 1)};
});
`;
fs.writeFileSync(path.join(__dirname, '..', 'coding-problems.js'), out);
console.log(`coding-problems.js written: ${specs.length} problems (${(out.length / 1024).toFixed(0)} KB)`);
